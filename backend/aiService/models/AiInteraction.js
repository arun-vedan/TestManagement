const mongoose = require('mongoose');
const crypto = require('crypto');

// WP-050 -- AiInteraction: the cost/audit log for every call this service
// makes to a provider (health check, /complete, /structured).
//
// RETENTION (explicit, stated default -- the WP-050 brief is verbatim:
// "NOT storing full customer text longer than needed -- make retention
// configurable"):
//
//   1. Metadata (who/what/how much/how long) is ALWAYS stored,
//      unconditionally: userId, projectId, provider, model, feature,
//      promptTokens/completionTokens/totalTokens, latencyMs, status,
//      errorCode, correlationId, createdAt. This is everything cost/audit
//      actually needs, and none of it is customer prompt/response text.
//
//   2. Prompt/response TEXT is stored in full ONLY when
//      AI_STORE_FULL_TEXT=true. THE DEFAULT IS FALSE. By default this
//      document stores a short preview (first AI_LOG_PREVIEW_CHARS
//      characters, default 200) plus a SHA-256 hash of the full text --
//      the hash lets ops/audit correlate two identical prompts (e.g. for
//      abuse investigation or future caching) without the raw customer
//      text ever touching disk.
//
//   3. Every document expires automatically via a Mongo TTL index on
//      `createdAt`, AI_LOG_RETENTION_DAYS days out. THE DEFAULT IS 30
//      DAYS. This is the "make retention configurable" knob: one env var,
//      no migration/backfill. (Mongo TTL indexes re-read
//      expireAfterSeconds from the index definition each sweep, so a
//      config change takes effect for already-written documents too, the
//      next time this service starts and Mongoose re-syncs the index --
//      not just for documents written after the change.)
//
// An AI audit log that silently hoards requirement/defect/test-case text
// forever is a privacy problem, not a feature -- this schema is built so
// that is not the default, and ops can see/change the knobs in one place
// (config/config.env.example) rather than by reading this file.
function resolveRetentionDays() {
  const raw = process.env.AI_LOG_RETENTION_DAYS;
  const parsed = raw !== undefined ? parseInt(raw, 10) : NaN;
  return Number.isInteger(parsed) && parsed > 0 ? parsed : 30;
}

function resolveStoreFullText() {
  return String(process.env.AI_STORE_FULL_TEXT || 'false').toLowerCase() === 'true';
}

function resolvePreviewChars() {
  const raw = process.env.AI_LOG_PREVIEW_CHARS;
  const parsed = raw !== undefined ? parseInt(raw, 10) : NaN;
  return Number.isInteger(parsed) && parsed > 0 ? parsed : 200;
}

// The ONE place that decides how much of a piece of text gets persisted --
// centralised so no controller can accidentally bypass the retention
// policy and log a raw prompt/response in full. Always returns a preview +
// hash; `full` is only set when AI_STORE_FULL_TEXT=true, and even then the
// caller (controllers/ai.js) only writes it into the *Full schema fields
// under that condition.
function shapeText(text) {
  if (!text) {
    return { preview: '', hash: null, full: undefined };
  }
  const str = String(text);
  const hash = crypto.createHash('sha256').update(str).digest('hex');
  const preview = str.slice(0, resolvePreviewChars());
  const full = resolveStoreFullText() ? str : undefined;
  return { preview, hash, full };
}

const AiInteractionSchema = new mongoose.Schema(
  {
    // Plain Mongo _id (WP-020c convention, same decision WP-043's
    // SavedView made -- see that model's header comment): no numeric `id`
    // field, nothing generated by a read-then-write against a unique
    // index, so concurrent writes here can never race the way
    // Project/testRepo/defect's `id` generator does.
    userId: { type: String, required: true, index: true },
    projectId: { type: Number, required: true, index: true },
    // Which aiService endpoint produced this interaction: 'health',
    // 'complete', 'structured'. Open string (not an enum) so a future
    // WP-051..053 caller can log its own feature name without a schema
    // change here.
    feature: { type: String, required: true, index: true },
    provider: { type: String, required: true },
    model: { type: String, required: true },
    promptPreview: { type: String },
    promptHash: { type: String },
    promptFull: { type: String }, // only populated when AI_STORE_FULL_TEXT=true
    responsePreview: { type: String },
    responseHash: { type: String },
    responseFull: { type: String }, // only populated when AI_STORE_FULL_TEXT=true
    promptTokens: { type: Number, default: 0 },
    completionTokens: { type: Number, default: 0 },
    totalTokens: { type: Number, default: 0 },
    latencyMs: { type: Number, required: true },
    status: { type: String, enum: ['ok', 'error'], required: true },
    errorCode: { type: String },
    correlationId: { type: String }
  },
  { timestamps: { createdAt: true, updatedAt: false } }
);

AiInteractionSchema.index({ projectId: 1, createdAt: -1 });
AiInteractionSchema.index({ userId: 1, createdAt: -1 });
// Retention knob (see header comment): TTL index on createdAt.
AiInteractionSchema.index({ createdAt: 1 }, { expireAfterSeconds: resolveRetentionDays() * 24 * 60 * 60 });

module.exports = {
  AiInteraction: mongoose.model('AiInteraction', AiInteractionSchema),
  shapeText,
  resolveRetentionDays,
  resolveStoreFullText,
  resolvePreviewChars
};
